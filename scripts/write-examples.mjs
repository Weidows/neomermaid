/**
 * Writes every built-in example out as a plain `.mmd` file so they can be
 * opened, diffed and dropped into an editor without touching the SDK.
 *
 *   node scripts/write-examples.mjs [outDir]
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const coreEntry = resolve(here, '..', 'packages', 'core', 'dist', 'index.js');
if (!existsSync(coreEntry)) {
  console.error('packages/core/dist/index.js is missing — run `npm run build:core` first.');
  process.exit(1);
}
const { EXAMPLES } = await import(`file://${coreEntry.replace(/\\/g, '/')}`);

const outDir = resolve(process.argv[2] ?? resolve(here, '..', 'examples'));
mkdirSync(outDir, { recursive: true });

let written = 0;
for (const example of EXAMPLES) {
  const header = `%% ${example.title} — ${example.description}\n%% preset hint: ${example.highlights?.join(', ') ?? ''}\n`;
  const file = resolve(outDir, `${example.id}.mmd`);
  const body = `${header}${example.source.trim()}\n`;
  let previous = '';
  try {
    previous = readFileSync(file, 'utf8');
  } catch {
    /* new file */
  }
  if (previous !== body) {
    writeFileSync(file, body);
    written += 1;
  }
}

const index = [
  '# Examples',
  '',
  'Generated by `npm run examples` from `packages/core/src/examples.ts` (do not edit by hand).',
  '',
  '| File | Shows off |',
  '| --- | --- |',
  ...EXAMPLES.map((e) => `| [\`${e.id}.mmd\`](./${e.id}.mmd) | ${e.title} — ${e.description} |`),
  '',
].join('\n');
writeFileSync(resolve(outDir, 'README.md'), index);

console.log(`examples: ${EXAMPLES.length} files in ${outDir} (${written} updated)`);
